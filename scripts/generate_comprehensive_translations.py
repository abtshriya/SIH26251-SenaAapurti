# Translate compound units, locations, and patterns
for s in phrases + sentences:
    trimmed = s.strip()
    if trimmed in translations:
        continue
    
    # 1. Parenthesized suffixes: "X (Y)"
    m_paren = re.match(r'^(.*?)\s*\((.*?)\)$', trimmed)
    if m_paren:
        base, inner = m_paren.group(1), m_paren.group(2)
        base_tr = translations.get(base, base)
        inner_tr = translations.get(inner, inner)
        if base_tr != base or inner_tr != inner:
            translations[trimmed] = f"{base_tr} ({inner_tr})"
            continue

    # 2. "X & Y"
    if ' & ' in trimmed:
        parts = trimmed.split(' & ')
        tr_parts = [translations.get(p.strip(), p.strip()) for p in parts]
        if any(tr_parts[i] != parts[i].strip() for i in range(len(parts))):
            translations[trimmed] = ' एवं '.join(tr_parts)
            continue

    # 3. "X - Y"
    if ' - ' in trimmed:
        parts = trimmed.split(' - ')
        tr_parts = [translations.get(p.strip(), p.strip()) for p in parts]
        if any(tr_parts[i] != parts[i].strip() for i in range(len(parts))):
            translations[trimmed] = ' - '.join(tr_parts)
            continue

    # 4. "X • Y"
    if ' • ' in trimmed:
        parts = trimmed.split(' • ')
        tr_parts = [translations.get(p.strip(), p.strip()) for p in parts]
        if any(tr_parts[i] != parts[i].strip() for i in range(len(parts))):
            translations[trimmed] = ' • '.join(tr_parts)
            continue

