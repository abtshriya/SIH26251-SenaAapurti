/**
 * HELPER QUERY FUNCTIONS FOR THE INDIAN ARMY COMMANDS & UNITS DATABASE
 */

/** Retrieve all 9 Commands */
export function getAllCommands(): ArmyCommand[] {
  return INDIAN_ARMY_COMMANDS;
}

/** Retrieve all Units */
export function getAllUnits(): ArmyUnit[] {
  return ALL_INDIAN_ARMY_UNITS;
}

/** Get Command by unique ID */
export function getCommandById(id: string): ArmyCommand | undefined {
  return INDIAN_ARMY_COMMANDS.find(c => c.id.toLowerCase() === id.toLowerCase() || c.code.toLowerCase() === id.toLowerCase());
}

/** Get Units by Command name or code */
export function getUnitsByCommand(commandQuery: string): ArmyUnit[] {
  const q = commandQuery.toLowerCase().trim();
  return ALL_INDIAN_ARMY_UNITS.filter(u => 
    u.command.toLowerCase().includes(q) || 
    (q === 'nc' && u.command === 'Northern Command') ||
    (q === 'wc' && u.command === 'Western Command') ||
    (q === 'ec' && u.command === 'Eastern Command') ||
    (q === 'sc' && u.command === 'Southern Command') ||
    (q === 'swc' && u.command === 'South Western Command') ||
    (q === 'cc' && u.command === 'Central Command') ||
    (q === 'artrac' && u.command === 'Army Training Command') ||
    (q === 'anc' && u.command === 'Andaman & Nicobar Command') ||
    (q === 'ahq' && u.command === 'Army Headquarters')
  );
}

/** Search Units by text */
export function searchArmyUnits(query: string): ArmyUnit[] {
  if (!query || !query.trim()) return ALL_INDIAN_ARMY_UNITS;
  const q = query.toLowerCase().trim();
  return ALL_INDIAN_ARMY_UNITS.filter(u => 
    u.name.toLowerCase().includes(q) ||
    u.id.toLowerCase().includes(q) ||
    u.station.toLowerCase().includes(q) ||
    u.sector.toLowerCase().includes(q) ||
    u.corps.toLowerCase().includes(q) ||
    u.command.toLowerCase().includes(q) ||
    u.officerName.toLowerCase().includes(q) ||
    u.type.toLowerCase().includes(q)
  );
}

/** National Army Summary Statistics */
export function getIndianArmyTelemetrySummary() {
  const totalUnits = ALL_INDIAN_ARMY_UNITS.length;
  const totalCommands = INDIAN_ARMY_COMMANDS.length;
  const avgReadiness = (ALL_INDIAN_ARMY_UNITS.reduce((sum, u) => sum + u.readiness, 0) / totalUnits).toFixed(1);
  const totalConvoys = ALL_INDIAN_ARMY_UNITS.reduce((sum, u) => sum + u.activeConvoys, 0);
  const totalPersonnel = ALL_INDIAN_ARMY_UNITS.reduce((sum, u) => sum + u.personnel, 0);
  const criticalRiskUnits = ALL_INDIAN_ARMY_UNITS.filter(u => u.riskLevel === 'Critical' || u.riskLevel === 'High').length;
  
  return {
    totalUnits,
    totalCommands,
    avgReadiness: Number(avgReadiness),
    totalConvoys,
    totalPersonnel,
    criticalRiskUnits,
    highAltitudeUnits: ALL_INDIAN_ARMY_UNITS.filter(u => u.sector.includes('ft') || u.command === 'Northern Command').length
  };
}
