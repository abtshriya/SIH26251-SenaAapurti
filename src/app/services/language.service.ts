  t(key: string | undefined | null): string {
    if (!key) return '';
    const lang = this.currentLang();
    if (lang === 'hi') {
      return this.translateText(key);
    }
    return this.translations[lang]?.[key] || this.translations['en']?.[key] || key;
  }

